ESTRUCTURES = {"enllac","oracio","nom","infinitiu","adverbi","final"}
REGISTRES = {"formal","neutre","informal"}

out, errs, ids = [], [], set()
for (cid, con, fun, est, reg, niv, sig, ex, tr, eq, dis, nota) in D:
    assert fun in FUNCIONS and est in ESTRUCTURES and reg in REGISTRES and niv in (1, 2, 3), cid
    assert cid not in ids, cid
    ids.add(cid)
    pat = r"\b" + r"\s+".join(map(re.escape, con.split())) + r"\b"
    hits = list(re.finditer(pat, ex, flags=re.I))
    if len(hits) != 1:
        errs.append(f"{cid}: «{con}» apareix {len(hits)} cops a «{ex}»"); continue
    m = hits[0]
    iniciFrase = m.start() == 0 or bool(re.search(r"[.!?]\s+$", ex[:m.start()]))
    low = lambda xs: [x.lower() for x in xs]
    if len(dis) < 3: errs.append(f"{cid}: calen ≥3 distractors")
    if len(set(low(dis))) != len(dis): errs.append(f"{cid}: distractors repetits")
    if con.lower() in low(dis) + low(eq): errs.append(f"{cid}: el connector és als seus distractors/equivalents")
    if set(low(dis)) & set(low(eq)): errs.append(f"{cid}: un distractor és equivalent")
    out.append({"id": cid, "connector": con, "funcio": fun, "estructura": est, "registre": reg,
                "nivell": niv, "significat": sig, "exemple": ex,
                "exempleMarcat": ex[:m.start()] + "**" + m.group() + "**" + ex[m.end():],
                "forat": ex[:m.start()] + "___" + ex[m.end():], "iniciFrase": iniciFrase,
                "traduccio": tr, "equivalents": eq, "distractors": dis, "nota": nota})

# un distractor mai pot ser equivalent d'un connector que sigui equivalent de la resposta (coherència creuada)
# trampes revisades a mà: mateixa funció però significat contrari o posició impossible
TRAMPES_OK = {("as-long-as","unless"),("provided-that","unless"),("in-case","unless"),("finally","firstly")}
per_con = {}
for o in out: per_con.setdefault(o["connector"].lower(), []).append(o)
for o in out:
    for d in o["distractors"]:
        for other in per_con.get(d.lower(), []):
            if (o["id"], d.lower()) in TRAMPES_OK: continue
            if o["funcio"] == other["funcio"] and other["estructura"] == o["estructura"]:
                errs.append(f"{o['id']}: el distractor «{d}» té la mateixa funció i estructura (podria ser correcte)")
if errs:
    print("\n".join(errs)); sys.exit(1)
json.dump({"versio": 1, "connectors": out}, open(sys.argv[1], "w", encoding="utf-8"), ensure_ascii=False, indent=1)
print(len(out), "connectors |", dict(Counter(o["nivell"] for o in out)), "|", dict(Counter(o["funcio"] for o in out)))
print("amb equivalents:", sum(1 for o in out if o["equivalents"]), "| inici de frase:", sum(o["iniciFrase"] for o in out))
